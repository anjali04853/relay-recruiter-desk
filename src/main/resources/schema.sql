CREATE TABLE IF NOT EXISTS posts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_key VARCHAR(64) UNIQUE NOT NULL, author VARCHAR(200) NOT NULL,
 company VARCHAR(200), body CLOB NOT NULL, location VARCHAR(200), country VARCHAR(2),
 published_at VARCHAR(40) NOT NULL, source_url VARCHAR(2000), keywords VARCHAR(500),
 demo BOOLEAN NOT NULL DEFAULT FALSE, created_at VARCHAR(40) NOT NULL
);
CREATE TABLE IF NOT EXISTS contacts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id BIGINT NOT NULL REFERENCES posts(id), email VARCHAR(320) UNIQUE NOT NULL,
 name VARCHAR(200), company VARCHAR(200), suppressed BOOLEAN DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS drafts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 contact_id BIGINT UNIQUE NOT NULL REFERENCES contacts(id),
 subject VARCHAR(500) NOT NULL, body CLOB NOT NULL,
 status VARCHAR(30) NOT NULL, updated_at VARCHAR(40) NOT NULL, error VARCHAR(500)
);
CREATE TABLE IF NOT EXISTS settings (setting_key VARCHAR(100) PRIMARY KEY, setting_value CLOB);
CREATE TABLE IF NOT EXISTS events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, message VARCHAR(1000), created_at VARCHAR(40)
);
